#!/usr/bin/env python3
"""Generate the universities seed migration and docs from the dataset.

Source of truth: backend/data/universities_bd.json

    python3 tools/universities/generate.py                 # docs only
    python3 tools/universities/generate.py --migration 00130_universities_update

Adding or fixing a university: edit the JSON, then generate a NEW migration
(never edit one that has shipped). The SQL is an idempotent upsert of the
whole dataset, so a new migration simply brings every database up to date.
Removing a domain needs a hand-written migration.

Writes:
  backend/migrations/<name>.sql   (only with --migration)
  docs/UNIVERSITIES.md            (always)
"""

import argparse
import collections
import json
import re
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[2]
DATA = BACKEND / "data" / "universities_bd.json"
DOCS = BACKEND.parent / "docs" / "UNIVERSITIES.md"

DOMAIN_RE = re.compile(r"^[a-z0-9-]+(\.[a-z0-9-]+)+$")
SLUG_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
# Must match the CHECK constraint in migrations/00105_university_domain_guard.sql
SHARED = {
    "ac.bd", "edu.bd", "gov.bd", "com.bd", "org.bd", "net.bd", "mil.bd", "info.bd",
    "co.bd", "sw.bd", "tv.bd", "edu", "com", "org", "net", "ac", "info", "io", "me",
    "bd", "gmail.com", "googlemail.com", "yahoo.com", "ymail.com", "outlook.com",
    "hotmail.com", "live.com", "msn.com", "icloud.com", "me.com", "aol.com",
    "proton.me", "protonmail.com", "zoho.com", "gmx.com", "mail.com", "yandex.com",
    "rediffmail.com",
}


def load():
    data = json.loads(DATA.read_text(encoding="utf-8"))
    unis = data["universities"]
    errors, seen_slug, seen_domain = [], set(), {}
    for u in unis:
        tag = u.get("slug") or u.get("name")
        if not SLUG_RE.match(u["slug"]) or u["slug"] in seen_slug:
            errors.append(f"{tag}: bad or duplicate slug")
        seen_slug.add(u["slug"])
        if u["kind"] not in ("public", "private"):
            errors.append(f"{tag}: kind must be public or private")
        if not 2 <= len(u["name"]) <= 120:
            errors.append(f"{tag}: name length")
        if u.get("name_bn") and len(u["name_bn"]) > 120:
            errors.append(f"{tag}: name_bn too long")
        if u.get("city") and len(u["city"]) > 60:
            errors.append(f"{tag}: city too long")
        if u.get("website") and not DOMAIN_RE.match(u["website"]):
            errors.append(f"{tag}: bad website {u['website']}")
        for d in u["sign_in_domains"]:
            if not DOMAIN_RE.match(d) or d != d.lower():
                errors.append(f"{tag}: bad domain {d}")
            if d in SHARED or re.match(r"^(yahoo|hotmail|outlook)\.", d):
                errors.append(f"{tag}: shared/free-mail domain {d} is not allowed")
            if d in seen_domain:
                errors.append(f"{tag}: domain {d} already belongs to {seen_domain[d]}")
            seen_domain[d] = u["slug"]
    if errors:
        sys.exit("dataset errors:\n  " + "\n  ".join(errors))
    return data, unis


def q(v):
    if v is None:
        return "NULL"
    return "'" + str(v).replace("'", "''") + "'"


def migration_sql(unis):
    rows = ",\n".join(
        f"    ({q(u['slug'])}, {q(u['name'])}, {q(u.get('name_bn'))}, {q(u.get('city'))}, "
        f"{q(u['kind'])}, {q(u.get('website'))})"
        for u in unis
    )
    domains = ",\n".join(
        f"    ({q(d)}, {q(u['slug'])})" for u in unis for d in u["sign_in_domains"]
    )
    slugs = ", ".join(q(u["slug"]) for u in unis)
    return f"""-- +goose Up
-- GENERATED by backend/tools/universities/generate.py from
-- backend/data/universities_bd.json. Do not edit by hand.
-- {len(unis)} universities, {sum(len(u['sign_in_domains']) for u in unis)} sign-in domains.

INSERT INTO universities (slug, name, name_bn, city, kind, website) VALUES
{rows}
ON CONFLICT (slug) DO UPDATE SET
    name    = EXCLUDED.name,
    name_bn = COALESCE(EXCLUDED.name_bn, universities.name_bn),
    city    = COALESCE(EXCLUDED.city, universities.city),
    kind    = EXCLUDED.kind,
    website = EXCLUDED.website;

INSERT INTO university_domains (domain, university_id)
SELECT d.domain, u.id FROM (VALUES
{domains}
) AS d(domain, slug)
JOIN universities u ON u.slug = d.slug
ON CONFLICT (domain) DO NOTHING;

-- +goose Down
-- Removes the seeded universities nobody has signed up with yet.
DELETE FROM universities
WHERE slug IN ({slugs})
  AND slug <> 'diu'
  AND NOT EXISTS (SELECT 1 FROM users WHERE users.university_id = universities.id);
"""


def suffix(domain):
    for s in (".ac.bd", ".edu.bd", ".gov.bd", ".org.bd"):
        if domain.endswith(s):
            return s[1:]
    return domain.rsplit(".", 1)[-1] if "." in domain else domain


def patterns(unis):
    out = []
    by_kind = collections.defaultdict(collections.Counter)
    for u in unis:
        if u.get("website"):
            by_kind[u["kind"]][suffix(u["website"])] += 1
    out.append("### Website domain endings\n")
    out.append("| Ending | Public | Private |\n|---|---|---|")
    endings = sorted(set(by_kind["public"]) | set(by_kind["private"]),
                     key=lambda e: -(by_kind["public"][e] + by_kind["private"][e]))
    for e in endings:
        out.append(f"| `.{e}` | {by_kind['public'][e]} | {by_kind['private'][e]} |")

    generic = {"student", "students", "std", "stud", "stu", "g", "ugrad"}
    prefixes = collections.Counter()
    per_unit = collections.Counter()
    cross = []
    for u in unis:
        site = u.get("website")
        held = set(u.get("held_domains", []))
        for d in u["student_email_domains"]:
            if site and d != site and d.endswith("." + site):
                label = d[: -len(site) - 1].split(".")[-1]
                if label in generic:
                    prefixes[label] += 1
                else:
                    per_unit[u["name"]] += 1
            elif site and d != site:
                cross.append((u["name"], site, d, d in held))
    out.append("\n### Student email subdomains (under the website domain)\n")
    out.append("| Prefix | Universities |\n|---|---|")
    for p, n in prefixes.most_common():
        out.append(f"| `{p}.` | {n} |")
    if per_unit:
        names = ", ".join(f"{n} ({c})" for n, c in per_unit.most_common())
        out.append(f"| one per department or programme | {len(per_unit)}: {names} |")

    out.append("\n### Students on a different domain than the website\n")
    out.append("| University | Website | Student domain | Status |\n|---|---|---|---|")
    for name, site, d, is_held in cross:
        status = "held: unverified, not accepted yet" if is_held else "accepted"
        out.append(f"| {name} | `{site}` | `{d}` | {status} |")
    return "\n".join(out)


def summary(unis):
    def share(kind, end):
        sites = [u["website"] for u in unis if u["kind"] == kind and u.get("website")]
        return sum(1 for w in sites if suffix(w) == end), len(sites)
    pa, pt = share("public", "ac.bd")
    ve, vt = share("private", "edu.bd")
    va, _ = share("private", "ac.bd")
    plain = sorted(u["website"] for u in unis if u.get("website") and suffix(u["website"]) in ("edu", "ac", "com"))
    with_student = sum(1 for u in unis if u["student_email_domains"])
    return f"""- **Public universities:** {pa} of {pt} websites end in `.ac.bd`; the rest mostly `.edu.bd`.
- **Private universities:** {ve} of {vt} use `.edu.bd` and {va} use `.ac.bd`.
- **Plain international endings:** {', '.join(f'`{w}`' for w in plain)}.
- **Students usually get a subdomain** of the website domain (`student.`, `std.`, `stud.`, `g.`, `ugrad.`, or one per department or programme, like UIU's `bscse.uiu.ac.bd`). The subdomain rule covers these automatically, so for most universities **the website domain alone is enough**. We found student-domain evidence for {with_student} universities; for the rest the website domain covers students who use it.
- **The exceptions matter:** some universities give students a different domain than their website, or were renamed and still receive mail on the old domain (aliases). These are listed explicitly; without them those students could not sign in.
- **Look-alike abbreviations are common** (`diu.edu.bd` Daffodil vs `diu.ac` Dhaka International; `sau.edu.bd` vs `sau.ac.bd`; `bmu.ac.bd` vs `bmu.edu.bd`). Always add exact domains; never guess from an abbreviation."""


def table(unis):
    lines = ["| University | City | Sign-in domains | Confidence |", "|---|---|---|---|"]
    for u in unis:
        name = u["name"] + (f"<br>{u['name_bn']}" if u.get("name_bn") else "")
        doms = ", ".join(f"`{d}`" for d in u["sign_in_domains"]) or "**none yet**"
        lines.append(f"| {name} | {u.get('city') or ''} | {doms} | {u['confidence']} |")
    return "\n".join(lines)


def docs(data, unis):
    pub = [u for u in unis if u["kind"] == "public"]
    pri = [u for u in unis if u["kind"] == "private"]
    no_domain = [u["name"] for u in unis if not u["sign_in_domains"]]
    held = [(u["name"], d) for u in unis for d in u.get("held_domains", [])]
    n_domains = sum(len(u["sign_in_domains"]) for u in unis)
    return f"""# Universities and student email domains

<!-- GENERATED by backend/tools/universities/generate.py. Edit backend/data/universities_bd.json instead. -->

VarsityKotha accepts a student only with their **university email** (email
code or university Google account). This page lists every university we
recognise and the email domains that map to it.

- **{len(unis)} universities** ({len(pub)} public, {len(pri)} private), **{n_domains} sign-in domains**
- Researched {data['researched_on']} from the University Grants Commission (UGC) lists and each university's own website
- Source of truth: [`backend/data/universities_bd.json`](../backend/data/universities_bd.json) (with source links per university)

## How matching works

1. The email's domain is matched against the sign-in domains **and all their subdomains**: `rafi@cse.du.ac.bd` → `du.ac.bd` → University of Dhaka.
2. The **longest** match wins, so a department or student subdomain never falls through to a different university.
3. Matching is on whole labels: `x@nottest.ac.bd` never matches `test.ac.bd`.
4. Shared suffixes (`ac.bd`, `edu.bd`) and free mail (`gmail.com`, `yahoo.com` …) can never be added. The database refuses them.

## Common patterns

{patterns(unis)}

### What this means

{summary(unis)}

## Gaps to fill

- **No domain yet** (students cannot sign in until one is added): {', '.join(no_domain) or 'none'}
- **Held back, needs verification:** {', '.join(f'{n} (`{d}`)' for n, d in held) or 'none'}
- When a student reports "my university email doesn't work", check their domain, add it to the JSON, and generate a new migration.

## Public universities ({len(pub)})

{table(pub)}

## Private universities ({len(pri)})

{table(pri)}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--migration", help="write backend/migrations/<name>.sql, e.g. 00120_bd_universities")
    args = ap.parse_args()
    data, unis = load()
    if args.migration:
        path = BACKEND / "migrations" / f"{args.migration}.sql"
        if path.exists():
            sys.exit(f"{path} exists; never rewrite a migration, pick a new number")
        path.write_text(migration_sql(unis), encoding="utf-8")
        print("wrote", path.relative_to(BACKEND.parent))
    DOCS.write_text(docs(data, unis), encoding="utf-8")
    print("wrote", DOCS.relative_to(BACKEND.parent))


if __name__ == "__main__":
    main()
